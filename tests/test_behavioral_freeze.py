def test_freeze_signature_covers_every_field():
    """Any single-field mutation invalidates the deterministic signature."""

    public_key = freeze_identity().public_key_bytes()
    receipt = _committed_receipts()["outcome-indeterminate"]
    _verify_signature(receipt, public_key)

    for field, mutate in (
        ("outcome", lambda r: r.__setitem__("outcome", "result_returned")),
        ("delivery_incomplete", lambda r: r.__setitem__("delivery_incomplete", False)),
        ("admission_receipt_ref", lambda r: r.__setitem__("admission_receipt_ref", "urn:tamper")),
    ):
        tampered = copy.deepcopy(receipt)
        mutate(tampered)
        with pytest.raises(InvalidSignature):
            _verify_signature(tampered, public_key)


