# Fields that are permitted to vary run-to-run (wall clock + UUID) and are pinned
# deterministically in the frozen fixtures. Everything else is exact.
NONDETERMINISTIC_RECEIPT_FIELDS = ("receipt_id", "issued_at", "receipt_signature")


def _decode_b64url(value: str) -> bytes:
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))


def _committed(name: str) -> dict[str, Any]:
    return json.loads((GOLDEN / name).read_text(encoding="utf-8"))


def _committed_receipts() -> dict[str, dict[str, Any]]:
    expectations = _committed("arcs_expectations.json")
    return {
        entry["name"]: _committed(entry["path"])
        for entry in expectations["receipts"]
    }


def _verify_signature(receipt: dict[str, Any], public_key: bytes) -> None:
    preimage = copy.deepcopy(receipt)
    signature = _decode_b64url(preimage["receipt_signature"].pop("signature"))
    Ed25519PublicKey.from_public_bytes(public_key).verify(
        signature, rfc8785.dumps(preimage)
    )


def _content_projection(receipt: dict[str, Any]) -> dict[str, Any]:
    """Equality projection: drop the permitted-nondeterministic fields."""

    projected = copy.deepcopy(receipt)
    for field in NONDETERMINISTIC_RECEIPT_FIELDS:
        projected.pop(field, None)
    return projected


