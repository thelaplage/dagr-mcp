SMUGGLED_RAW_RESULT = (
    "BEGIN tool transcript\n"
    "row 1: customer record balance 4210.55\n"
    "row 2: internal note — do not disclose to caller\n"
    "END transcript"
)


@requires_arcs
def test_freeze_resigned_non_boolean_delivery_field_is_rejected_by_arcs(tmp_path):
    """A genuinely re-signed receipt that swaps the delivery Boolean for raw
    material must be rejected on a *profile* (non-Boolean governance) ground, not
    merely on signature invalidity. This freezes the guard the arcs-verify merge
    da89ebe added, closing the A0 cross-repo gap."""

    identity = freeze_identity()
    emitter = SignedReceiptEmitter(identity=identity, sink=RawEnvelopeFileSink(tmp_path))
    receipt_id = emitter.emit_outcome(
        context=ReceiptContext(
            runtime_instance_id="r", boundary_id="b", policy_pack_id="p",
            policy_pack_version="1", subject_ref="s", logical_call_id="c",
            actor_ref="a", binding_version="fastmcp.middleware.v0.1",
        ),
        admission_receipt_ref="urn:srs:receipt:admission:1",
        outcome="indeterminate",
        additional_attestation_limits=(
            "The middleware is installed once at the institutional trust boundary; "
            "receipts attest only to observations at that boundary.",
        ),
        binding_owned_fields={
            "request_cancelled": True,
            "execution_state_unknown": True,
            "delivery_incomplete": True,
        },
    )
    receipt = next(
        json.loads(p.read_text())
        for p in tmp_path.glob("urn_srs_receipt_*.json")
        if json.loads(p.read_text())["receipt_id"] == receipt_id
    )

    forged = copy.deepcopy(receipt)
    forged["delivery_incomplete"] = SMUGGLED_RAW_RESULT
    forged.pop("receipt_signature", None)
    resigned = identity.sign_envelope(forged)
    assert resigned["delivery_incomplete"] == SMUGGLED_RAW_RESULT

    report = _arcs_verify_receipt(
        resigned, identity.trust_bundle(), schema_path=SCHEMA_PATH, selected_profile=MCP_PROFILE
    ).to_dict()

    # The re-sign is genuine: the signature is valid.
    assert report["signature_valid"] is True, report
    # Rejection is a profile-ground rejection, not signature invalidity.
    assert report["passed"] is False, report
    assert report["profile"] is False, report
    assert (
        "profile.non_boolean_governance_field:delivery_incomplete"
        in report["failure_codes"]
    ), report
