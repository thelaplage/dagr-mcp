def test_freeze_outcome_vocabulary_and_attestation_limits():
    receipts = _committed_receipts()

    # result_returned / error_returned carry the RESULT_LIMIT and a result_digest.
    for name, outcome in (
        ("outcome-result-returned", "result_returned"),
        ("outcome-error-returned", "error_returned"),
    ):
        r = receipts[name]
        assert r["outcome"] == outcome
        assert r["result_digest"].startswith("sha256:")
        assert srs_receipts.RESULT_LIMIT in r["attestation_limits"]

    # task_submitted carries the TASK_LIMIT.
    task = receipts["outcome-task-submitted"]
    assert task["outcome"] == "task_submitted"
    assert srs_receipts.TASK_LIMIT in task["attestation_limits"]

    # exception carries the exception class in the mcp extension, no result_digest.
    exc = receipts["outcome-exception"]
    assert exc["outcome"] == "exception"
    assert exc["extensions"]["mcp"]["exception_class"] == "TimeoutError"
    assert "result_digest" not in exc

    # indeterminate is the cancellation/timeout outcome.
    indet = receipts["outcome-indeterminate"]
    assert indet["outcome"] == "indeterminate"
    assert "result_digest" not in indet


