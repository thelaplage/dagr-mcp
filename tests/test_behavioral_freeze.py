def test_freeze_cancellation_fields_are_boolean_only_and_indeterminate_only(tmp_path):
    identity = freeze_identity()
    emitter = SignedReceiptEmitter(identity=identity, sink=RawEnvelopeFileSink(tmp_path))
    base = dict(
        runtime_instance_id="r", boundary_id="b", policy_pack_id="p",
        policy_pack_version="1", subject_ref="s", logical_call_id="c",
        actor_ref="a", binding_version="fastmcp.middleware.v0.1",
    )

    # Non-indeterminate outcome rejects any cancellation field.
    with pytest.raises(ReceiptContentError, match="only on indeterminate"):
        emitter.emit_outcome(
            context=ReceiptContext(**base),
            admission_receipt_ref="urn:srs:receipt:admission:1",
            outcome="result_returned",
            result_digest="sha256:" + "e" * 64,
            binding_owned_fields={"request_cancelled": True},
        )
    # Non-boolean cancellation value is refused before signing.
    with pytest.raises(ReceiptContentError, match="must be boolean"):
        emitter.emit_outcome(
            context=ReceiptContext(**base),
            admission_receipt_ref="urn:srs:receipt:admission:1",
            outcome="indeterminate",
            binding_owned_fields={"delivery_incomplete": "leaked rows"},
        )
    # Unknown binding-owned field is refused.
    with pytest.raises(ReceiptContentError, match="unknown binding-owned field"):
        emitter.emit_outcome(
            context=ReceiptContext(**base),
            admission_receipt_ref="urn:srs:receipt:admission:1",
            outcome="indeterminate",
            binding_owned_fields={"result_summary": True},
        )
    assert not list(tmp_path.glob("urn_srs_receipt_*.json"))


