def test_freeze_argument_digest_is_rfc8785_sha256():
    # sha256_digest canonicalizes with RFC 8785 JCS and prefixes sha256:.
    digest = sha256_digest({"b": 2, "a": 1})
    assert digest == sha256_digest({"a": 1, "b": 2})  # key-order independent
